const {chromium}=require(process.env.RELICA_PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const output=__dirname+'/../output';fs.mkdirSync(output,{recursive:true});
 const browser=await chromium.launch({headless:true,...(process.env.RELICA_BROWSER_PATH?{executablePath:process.env.RELICA_BROWSER_PATH}:{channel:'msedge'})});
 try{
 const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});page.on('response',r=>{if(r.status()>=400)errors.push(r.status()+' '+r.url());});
 await page.route('**/public-config.js',r=>r.fulfill({contentType:'text/javascript',body:"window.RELICA_CONFIG={url:'',key:'',google:false};"}));await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
 assert(await page.locator('#entrance').isVisible());
 assert(!(await page.locator('#site').isVisible()));
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:output+'/entrance-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'입장하기',exact:true}).click();
 assert(await page.locator('[data-view="home"]').isVisible());
 assert.equal(await page.locator('#home-members .member-card').count(),4);
 await page.screenshot({path:output+'/home-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'로그인',exact:true}).click();
 assert(await page.locator('#auth-dialog').isVisible());
 await page.getByRole('tab',{name:'회원가입',exact:true}).click();
 assert(await page.locator('#confirm-field').isVisible());
 await page.locator('#email').fill('preview@example.com');
 await page.locator('#password').fill('preview1234');
 await page.locator('#confirm-password').fill('preview1234');
 await page.getByRole('button',{name:'회원가입',exact:true}).click();
 assert((await page.locator('#auth-status').textContent()).includes('전송하거나 저장하지 않습니다'));
 await page.screenshot({path:output+'/signup-desktop.png'});
 await page.keyboard.press('Escape');
 assert(!(await page.locator('#auth-dialog').isVisible()));
 // dialog close 이벤트는 닫힘 표시 다음 작업에서 전달됩니다. 실제 초기화 완료를 기다립니다.
 await page.waitForFunction(()=>document.querySelector('#password').value==='',{},{timeout:1500});
 assert.equal(await page.locator('#password').inputValue(),'');
 assert(await page.locator('#login').evaluate(el=>el===document.activeElement));
 await page.getByRole('button',{name:'아렌 전사 소개',exact:true}).click();
 assert((await page.locator('#member-title').textContent()).includes('아렌'));
 assert.equal(await page.locator('.palette span').count(),5);
 await page.keyboard.press('Escape');
 await page.locator('nav').getByRole('button',{name:'미니 게임',exact:true}).click();
 assert(await page.locator('[data-view="game"]').isVisible());
 await page.getByRole('button',{name:'셀렌 · 마법사',exact:true}).click();
 assert.equal(await page.locator('#preview-member').textContent(),'SELENE / MAGE');
 await page.locator('nav').getByRole('button',{name:'클래스 테스트',exact:true}).click();
 assert(await page.locator('[data-view="test"]').isVisible());
 await page.locator('nav').getByRole('button',{name:'RELICA',exact:true}).click();
 assert(await page.locator('[data-view="relica"]').isVisible());
 await page.getByRole('button',{name:'입장 화면 다시 보기'}).click();
 assert(await page.locator('#entrance').isVisible());
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:output+'/entrance-mobile.png',fullPage:true});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.getByRole('button',{name:'입장하기',exact:true}).click();
 await page.screenshot({path:output+'/home-mobile.png',fullPage:true});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.getByRole('button',{name:'로그인',exact:true}).click();
 assert(await page.locator('#auth-dialog').isVisible());
 await page.screenshot({path:output+'/login-mobile.png'});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.equal(await page.evaluate(()=>localStorage.length),0);
 assert.deepEqual(errors,[]);
 console.log('PASS: desktop/mobile entrance, entry, 4 member cards, modal signup, Escape/focus restore, password clearing, menus, character preview, no horizontal overflow, no browser errors, no local credential storage.');
 console.log('Screenshots: '+output);
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
